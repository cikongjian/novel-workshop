/**
 * 按题材返回命名风格建议
 */
export function getNamingStyleForGenre(genre: string): string {
  const g = genre.toLowerCase();
  if (g.includes('xianxia') || g.includes('xuanhuan') || g.includes('fantasy-upgrade')) {
    return [
      '题材：玄幻/仙侠/升级文',
      '- 主角名可用古雅字（如：谦、衡、衍、湛、钧、砺、叙、叙、洵）',
      '- 但避免"墨/尘/逸/凌/辰/殇"等网文高频字',
      '- 配角可用单字名（古人常见），不要全是双字名',
      '- 反派可有威压感（如：厉、肃、衡），但不要走"夜凌风/冷月心"路线',
    ].join('\n');
  }
  if (g.includes('romance') || g.includes('sweet')) {
    return [
      '题材：言情/甜宠文',
      '- 主角名要有现代感和辨识度，但不要用"顾清辞/陆景深/沈夜"模板',
      '- 男主可接地气（如：周叙、方晋、徐敬业），避免"霸总"模板名',
      '- 女主避免"苏晚晴/林溪/苏陌"模板，可用：沈知意、方念、谢知微',
      '- 配角可有烟火气（大壮、翠花、阿芬），增加真实感',
    ].join('\n');
  }
  if (g.includes('urban') || g.includes('modern') || g.includes('career')) {
    return [
      '题材：都市/现代/职场文',
      '- 名字要符合当代真实命名习惯，参考真实人口姓名分布',
      '- 男主可用：建国、伟、强、磊、涛、鹏、浩、宇、泽、子轩',
      '- 女主可用：丽、娟、芳、霞、婷、雪、雨涵、欣怡、子萱',
      '- 避免所有"诗意堆砌型"名字，配角多用普通名字',
    ].join('\n');
  }
  if (g.includes('history') || g.includes('ancient')) {
    return [
      '题材：历史/古风文',
      '- 古代多用单字名或"之/子/公/伯/仲"等字',
      '- 字义偏向德行、自然、典籍（文、武、德、仁、义、礼、智、信、松、竹、梅、兰）',
      '- 示例：赵文谦、孙仲谋、李德明、周敬之',
      '- 避免用现代名字（建国、伟强）',
    ].join('\n');
  }
  if (g.includes('scifi') || g.includes('apocalypse') || g.includes('wasteland')) {
    return [
      '题材：科幻/末世文',
      '- 可用代号、编号、单字名（如：零、壹、K、X-01）',
      '- 也可用普通现代名（陈安、林野、徐青）',
      '- 避免玄幻化命名（不用"墨煌/凤栖/夜尊"）',
    ].join('\n');
  }
  return [
    '题材：通用',
    '- 单双字名要合理分配，不要全是双字名',
    '- 主角名要有辨识度，但不要过于浮夸',
    '- 配角名要简洁易记，可接地气',
  ].join('\n');
}

/**
 * 检查一个名字是否命中 AI 模板黑名单
 */
export function isAiTemplateName(name: string): boolean {
  const trimmed = name.trim();
  if (!trimmed) return false;
  return AI_TEMPLATE_NAMES.some(
    (n) => n === trimmed || trimmed.startsWith(n) || n.startsWith(trimmed),
  );
}

/**
 * 检查名字是否使用了被滥用的高频字
 */
export function usesHighFreqChars(name: string): string[] {
  const hits: string[] = [];
  for (const ch of HIGH_FREQ_NAME_CHARS) {
    if (name.includes(ch)) hits.push(ch);
  }
  return hits;
}
